"""Generate test/sql/regression_graph.test (run after `make release`: python3 scripts/gen_regression_tests.py) from the AnzoGraph-verified oracle queries.

Expected results come from running each query through the locally built DuckDB CLI; every query
listed here returned an identical result set on AnzoGraph 3.5.0 in the differential test.
"""
import os, subprocess, tempfile

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
CLI = f'{REPO}/build/release/duckdb'
MAP = 'test/regression/hr_mapping.ttl'

SETUP = [
    "CREATE TABLE emp AS SELECT * FROM (VALUES (10, 'Ann', 1, 52000), (11, 'Bob', 2, 61000), (12, 'Cid', 1, 48000), (13, 'Dee', NULL, 70000)) t(id, name, company_id, salary)",
    "CREATE TABLE company_src AS SELECT * FROM (VALUES (1, 'Acme'), (2, 'Globex'), (3, 'Initech')) t(id, name)",
    "COPY company_src TO '{TEST_DIR}/regression_company.parquet' (FORMAT parquet)",
    "CREATE VIEW company AS SELECT * FROM '{TEST_DIR}/regression_company.parquet'",
    "CREATE TABLE onto AS SELECT * FROM read_rdf('test/regression/ontology.ttl', prefix_expansion = true)",
    "CREATE VIEW onto_iri AS SELECT subject, predicate, object FROM onto WHERE object LIKE 'http%'",
    "CREATE VIEW onto_lit AS SELECT subject, predicate, object FROM onto WHERE object NOT LIKE 'http%'",
]

P = 'PREFIX ex: <http://example.com/ns#> PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#> '
CASES = [  # (title, sparql, sort)
    ('Join across a native table and a Parquet view', 'SELECT ?e ?c WHERE { ?p ex:name ?e ; ex:worksFor ?co . ?co ex:name ?c }', True),
    ('OPTIONAL keeps the employee without a company', 'SELECT ?e ?c WHERE { ?p a ex:Employee ; ex:name ?e OPTIONAL { ?p ex:worksFor/ex:name ?c } }', True),
    ('UNION over two classes', 'SELECT ?n WHERE { { ?x a ex:Employee ; ex:name ?n } UNION { ?x a ex:Company ; ex:name ?n } }', True),
    ('Numeric FILTER on an xsd:integer column', 'SELECT ?e WHERE { ?p ex:name ?e ; ex:salary ?s FILTER(?s > 50000) }', True),
    ('String functions in FILTER', 'SELECT ?e WHERE { ?p a ex:Employee ; ex:name ?e FILTER(STRSTARTS(LCASE(?e), "a") || CONTAINS(?e, "e")) }', True),
    ('COUNT with GROUP BY through a property path', 'SELECT ?c (COUNT(?p) AS ?n) WHERE { ?p ex:worksFor/ex:name ?c } GROUP BY ?c', True),
    ('MIN and MAX', 'SELECT (MIN(?s) AS ?lo) (MAX(?s) AS ?hi) WHERE { ?p ex:salary ?s }', True),
    ('ORDER BY DESC with LIMIT', 'SELECT ?e ?s WHERE { ?p ex:name ?e ; ex:salary ?s } ORDER BY DESC(?s) LIMIT 2', False),
    ('FILTER NOT EXISTS', 'SELECT ?c WHERE { ?co a ex:Company ; ex:name ?c FILTER NOT EXISTS { ?p ex:worksFor ?co } }', True),
    ('MINUS', 'SELECT ?c WHERE { ?co a ex:Company ; ex:name ?c MINUS { ?p ex:worksFor ?co } }', True),
    ('BIND with CONCAT and STR', 'SELECT ?label WHERE { ?p a ex:Employee ; ex:name ?e ; ex:salary ?s BIND(CONCAT(?e, ":", STR(?s)) AS ?label) }', True),
    ('VALUES', 'SELECT ?e WHERE { VALUES ?e { "Ann" "Dee" "Zed" } ?p ex:name ?e }', True),
    ('Subclass reasoning with rdfs:subClassOf*', 'SELECT ?n ?t WHERE { ?x a ?t ; ex:name ?n . ?t rdfs:subClassOf* ex:Party }', True),
    ('Domain-based reasoning: sequence path ending in a closure', 'SELECT DISTINCT ?x WHERE { ?x ?p ?v . ?p rdfs:domain/rdfs:subClassOf* ex:Party }', True),
    ('Ontology labels joined to data', 'SELECT ?n ?l WHERE { ?x a ?t ; ex:name ?n . ?t rdfs:label ?l }', True),
    ('Variable predicate on one subject', 'SELECT ?p ?o WHERE { <http://data.example.com/person/10> ?p ?o }', True),
    ('DATATYPE() reports the mapped datatype', 'SELECT ?e (DATATYPE(?s) AS ?dt) WHERE { ?p ex:name ?e ; ex:salary ?s }', True),
    ('isIRI() separates links from values', 'SELECT ?o (isIRI(?o) AS ?iri) WHERE { <http://data.example.com/person/11> ?p ?o }', True),
]


def run(sql, tmp):
    script = "LOAD 'build/release/extension/rdf/rdf.duckdb_extension';\n" + '.mode list\n.separator "\t"\n.headers off\n.nullvalue NULL\n' + ';\n'.join(s.replace('{TEST_DIR}', tmp) for s in SETUP) + ';\n' + sql + ';\n'
    out = subprocess.run([CLI, '-unsigned', '-no-agent'], input=script, capture_output=True, text=True, cwd=REPO)
    if out.returncode or out.stderr.strip():
        raise SystemExit(f'failed: {sql}\n{out.stderr}')
    return [line for line in out.stdout.splitlines() if line != '']


def columns(sparql):
    head = sparql.split('WHERE')[0]
    return head.count('?') - head.count('(') if '(' in head else head.count('?')


lines = [
    '# name: test/sql/regression_graph.test',
    '# description: SPARQL over a native table, a Parquet view and an ontology loaded with read_rdf.',
    '#   Every query here returned the same result set on AnzoGraph 3.5.0 (differential test,',
    '#   see ako/DuckDbRdfTest). Generated by scripts/gen_regression_tests.py; edit the generator, not this file.',
    '# group: [sql]',
    '',
    'require rdf',
    '',
    'require parquet',
    '',
]
for s in SETUP:
    lines += ['statement ok', s + ';', '']
with tempfile.TemporaryDirectory() as tmp:
    for title, sparql, sort in CASES:
        sql = f"SELECT * FROM execute_sparql('{P}{sparql}', '{MAP}')"
        rows = run(sql, tmp)
        if sort:
            rows = ['\t'.join(r) for r in sorted(tuple(x.split('\t')) for x in rows)]
        ncol = len(rows[0].split('\t')) if rows else columns(sparql)
        lines += [f'# {title}', f"query {'T' * ncol}{' rowsort' if sort else ''}", sql, '----', *rows, '']
    # ASK returns a single boolean column
    ask = f"SELECT * FROM execute_sparql('{P}ASK {{ ?p ex:name \"Bob\" }}', '{MAP}')"
    rows = run(ask, tmp)
    lines += ['# ASK', 'query T', ask, '----', *rows, '']

open(f'{REPO}/test/sql/regression_graph.test', 'w').write('\n'.join(lines))
print('wrote', len(CASES) + 1, 'cases')
